# prompt_builder.py

from typing import List

def build_prompt(mbti_keywords: List[str], hobby_keywords: List[str]) -> str:
    return (
        "아래의 성격과 취미 키워드를 참고하여 참신하고 창의적이며 다양한 표현을 활용한 재미있는 별명을 5개 만들어 주세요.\n"
        "각 별명은 아래의 규칙을 따라야 합니다.\n"
        "\n"
        "[규칙]\n"
        "1. 동물 또는 귀여운 캐릭터를 반드시 포함합니다 (예: 햄찌, 북극곰, 오리, 판다, 너구리 등 다양하게).\n"
        "2. 유머러스하거나 독특한 의성어, 의태어, 혹은 색다른 표현을 사용합니다 (예: 뽀글이, 달콩이, 몽실, 퐁당, 꼬물).\n"
        "3. 이전에 자주 쓰였던 표현인 '깡총이', '방울방울', '방울', '햄스터', '토끼', '펭귄'은 되도록 피하고 참신한 단어를 사용합니다.\n"
        "4. 한글로만 작성하고, 글자 수는 공백 없이 8자 이내로 제한합니다.\n"
        "\n"
        f"[MBTI 키워드]: {', '.join(mbti_keywords[:4])}\n"
        f"[취미 키워드]: {', '.join(hobby_keywords[:4])}\n"
        "\n"
        "[별명 예시]\n"
        "1. 별콩너구리\n"
        "2. 몽글달곰이\n"
        "3. 꿈빛다람이\n"
        "4. 꼬물이판다\n"
        "5. 뽀송구름냥\n"
        "\n"
        "위 조건을 바탕으로 창의적으로 별명을 만들어 번호를 붙여 출력해주세요."
    )
