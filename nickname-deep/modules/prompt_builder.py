# prompt_builder.py

from typing import List


def build_prompt(mbti_keywords: List[str], hobby_keywords: List[str]) -> str:
    return (
        "당신은 창의적인 별명을 만드는 전문가입니다. 아래의 성격(MBTI)과 취미 키워드를 참고해, "
        "동물이나 귀여운 캐릭터와 조합된 참신한 한글 별명 5개를 만들어주세요.\n"
        "\n"
        "[규칙]\n"
        "1. 동물이나 귀여운 상상 캐릭터를 반드시 포함하세요.(예: 포유류, 조류, 파충류, 어류, 곤충 등)\n"
        "2. 의성어, 의태어, 감성어를 활용해 개성 있게 만드세요.\n"
        "3. 별명은 한글로만, 공백 없이 8자 이내로 작성하세요.\n"
        "4. 반드시 **별명** 형식으로 출력하세요.\n"
        "\n"
        f"[MBTI 키워드]: {', '.join(mbti_keywords[:8])}\n"
        f"[취미 키워드]: {', '.join(hobby_keywords[:4])}\n"
        "\n"
        "[창의적인 조합 방법]\n"
        "1. 동물/캐릭터 + 성격 특징 (예: **활발한토끼**)\n"
        "2. 의성어 + 동물/캐릭터 (예: **뽀글곰이**)\n"
        "3. 감성어 + 동물/캐릭터 (예: **달콩다람이**)\n"
        "4. 취미 + 동물/캐릭터 (예: **달리기강아지**)\n"
        "5. 성격 + 취미 + 동물/캐릭터 (예: **활발달리기고양이**)\n"
        "\n"
        "위 규칙과 조합 방법을 참고하여, 주어진 키워드에 맞는 창의적인 별명 8개를 만들어주세요. "
        "각 별명은 반드시 **별명** 형식으로 출력해주세요."
    )